static bool check_declaration(const char *line, FILE *out, char *project_name)
{
	StrView sv = sv_trim(sv_fromc(line));
	StrView type_sv;
	const char *kind_str = NULL;

	if (sv_starts(sv, SV("Executable "))) {
		type_sv = SV("Executable");
		kind_str = "    .kind = T_EXECUTABLE,\n";
	} else if (sv_starts(sv, SV("Library "))) {
		type_sv = SV("Library");
		kind_str = "    .kind = T_LIBRARY,\n";
	} else if (sv_starts(sv, SV("Module "))) {
		type_sv = SV("Module");
	} else if (sv_starts(sv, SV("Project "))) {
		type_sv = SV("Project");
	} else {
		return false;
	}

	StrView after_type = sv_trim(sv_sub(sv, type_sv.len, sv.len - type_sv.len));
	StrView name_sv, rest;
	if (!sv_split(after_type, '=', &name_sv, &rest)) {
		return false;
	}
	name_sv = sv_trim(name_sv);
	rest = sv_trim(rest);
	if (sv_empty(name_sv) || !sv_starts(rest, SV("{"))) {
		return false;
	}

	fputs(line, out);
	if (kind_str) {
		fputs(kind_str, out);
	}
	fprintf(out, "    .name = \"%.*s\",\n", (int)name_sv.len, name_sv.data);
	if (sv_eq(type_sv, SV("Project"))) {
		usize copy_len = name_sv.len < 63 ? name_sv.len : 63;
		memcpy(project_name, name_sv.data, copy_len);
		project_name[copy_len] = '\0';
	}
	return true;
}

static const char *get_array_cast(StrView line_sv)
{
	if (sv_contains(line_sv, SV(".targets")) || sv_contains(line_sv, SV(".deps")))
		return "(void*[])";
	if (sv_contains(line_sv, SV(".mods")))
		return "(Module*[])";
	return "(const char*[])";
}

static char *find_closing_brace(char *s, char *last_ch)
{
	bool in_str = false;
	for (char *p = s; *p; ++p) {
		if (in_str && *p == '\\' && *(p + 1)) {
			++p;
			continue;
		}
		if (*p == '"')
			in_str = !in_str;
		if (!in_str && p[0] == '/' && p[1] == '/')
			break;
		if (!in_str && *p == '}')
			return p;
		if (!isspace((unsigned char)*p) && last_ch)
			*last_ch = *p;
	}
	return NULL;
}

static void attach_header(FILE *out)
{
	fprintf(out, "// Auto-generated by Nour. DO NOT EDIT.\n");
	const char *header = (const char *)include_nour_h;
	size_t len = include_nour_h_len;
	const char *nl = memchr(header, '\n', len);
	if (nl) {
		const char *body = nl + 1;
		size_t body_len = len - (size_t)(body - header);
		fwrite(body, 1, body_len, out);
	}
	fputs(section_banner("Project Manifest"), out);
}

static void attach_entrypoint(FILE *out, const char *project_name)
{
	if (project_name[0]) {
		fputs(section_banner("Entrypoint"), out);
		fprintf(out, "Project *nour_get_project(void) { return &%s; }\n", project_name);
	}
}

#include <stdlib.h>

Result preprocess_stream(FILE *in, FILE *out, const char *source_name)
{
	const char *src_name = source_name ? source_name : "<stream>";
	attach_header(out);

	char line[1024];
	char project_name[64] = { 0 };
	bool in_array = false;
	char last_ch = 0;

	while (fgets(line, sizeof(line), in)) {
		StrView line_sv = sv_fromc(line);
		StrView trimmed = sv_trim(line_sv);
		if (sv_starts(trimmed, SV("//"))) {
			fputs(line, out);
			continue;
		}

		if (!in_array && check_declaration(line, out, project_name))
			continue;

		if (in_array) {
			char *close_brace = find_closing_brace(line, &last_ch);

			if (close_brace) {
				*close_brace	= '\0';
				bool need_comma = last_ch && last_ch != ',';
				fprintf(out, "%s%s    NULL\n\t}%s", line, need_comma ? "," : "", close_brace + 1);
				in_array = false;
			} else {
				fputs(line, out);
			}
			continue;
		}

		char *open_brace = strchr(line, '{');
		char *equal = strchr(line, '=');
		if (open_brace && equal && open_brace > equal) {
			const char *cast = get_array_cast(line_sv);
			char *close_brace = find_closing_brace(open_brace + 1, NULL);

			if (close_brace) {
				*open_brace	 = '\0';
				*close_brace = '\0';
				StrView body_sv =
					sv_trim(sv_new(open_brace + 1, (usize)(close_brace - (open_brace + 1))));
				bool empty = sv_empty(body_sv);
				bool has_trailing_comma = sv_ends(body_sv, SV(","));
				const char *sep = (empty || has_trailing_comma) ? " " : ", ";
				fprintf(out, "%s%s{%s%sNULL }%s", line, cast, open_brace + 1, sep, close_brace + 1);
			} else {
				*open_brace = '\0';
				char *after = open_brace + 1;
				in_array = true;
				last_ch = 0;
				find_closing_brace(after, &last_ch);
				fprintf(out, "%s%s{%s%s", line, cast, after, strchr(after, '\n') ? "" : "\n");
			}
			continue;
		}
		fputs(line, out);
	}

	if (in_array) {
		return Err("Unclosed array in '%s'", src_name);
	}

	if (!project_name[0]) {
		return Err("No Project declaration found in '%s'", src_name);
	}

	attach_entrypoint(out, project_name);
	return Ok(NULL);
}

Result preprocess_str(const char *input_str, char **output_str)
{
	if (!input_str || !output_str) {
		return Err("Null pointer passed to preprocess_str");
	}
	*output_str = NULL;

	if (!input_str[0]) {
		return Err("No Project declaration found in '<memory>'");
	}

	FILE *in = fmemopen((void *)input_str, strlen(input_str), "r");
	if (!in) {
		return Err("fmemopen failed: %s", strerror(errno));
	}
	defer(fclose, in);

	char *out_buf = NULL;
	size_t out_size = 0;
	FILE *out = open_memstream(&out_buf, &out_size);
	if (!out) {
		return Err("open_memstream failed: %s", strerror(errno));
	}

	Result res = preprocess_stream(in, out, "<memory>");
	fclose(out);

	if (!res.ok) {
		free(out_buf);
		return res;
	}

	*output_str = out_buf;
	return Ok(out_buf);
}

Result preprocess(const char *input_path, const char *output_path)
{
	FILE *in = fopen(input_path, "r");
	if (!in) {
		return Err("Failed to open input file '%s': %s", input_path, strerror(errno));
	}
	defer(fclose, in);

	FILE *out = fopen(output_path, "w");
	if (!out) {
		return Err("Failed to create output file '%s': %s", output_path, strerror(errno));
	}

	Result res = preprocess_stream(in, out, input_path);
	fclose(out);

	if (!res.ok) {
		remove(output_path);
	}

	return res;
}
